def get_language() -> str:
    """Return the currently active language code."""
    global _current_language
    return _current_language


def set_language(lang_code: str) -> None:
    """Set the active language ('en' or 'id')."""
    global _current_language
    if lang_code in TRANSLATIONS:
        _current_language = lang_code


def t(key: str, **kwargs: Any) -> str:
    """
    Translate a key into the active language string.
    Falls back to English if key is missing in active language.
    If key is completely missing, returns the key itself.
    """
    lang = get_language()
    text = TRANSLATIONS.get(lang, {}).get(key)
    if text is None:
        text = TRANSLATIONS.get("en", {}).get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text

PRESET_KEY_MAP: dict[str, str] = {
    "3 days before": "preset_3_days_before",
    "1 day before": "preset_1_day_before",
    "12 hours before": "preset_12_hours_before",
    "3 hours before": "preset_3_hours_before",
    "1 hour before": "preset_1_hour_before",
    "30 minutes before": "preset_30_minutes_before",
    "At deadline": "preset_at_deadline",
    "Custom": "preset_custom",
}


def translate_preset(preset_label: str | None) -> str:
    """Translate a reminder preset label into the active language."""
    if not preset_label:
        return t("reminder_label")
    key = PRESET_KEY_MAP.get(preset_label)
    if key:
        return t(key)
    return preset_label
